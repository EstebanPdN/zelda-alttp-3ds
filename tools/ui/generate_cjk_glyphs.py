#!/usr/bin/env python3
"""Generate engine/src/platform/linux/ui_glyphs_cjk.h: the Chinese glyphs the port's own
screens draw.

One set: exactly the characters the port's strings use, at the three sizes the
screens draw (10 and 12 px Fusion Pixel, 16 px GNU Unifont). Text the port does
not own - a release note fetched from GitHub, a mod's description - is not
covered; add its characters to the strings (or extend this tool's sources) and
bake again.

The fonts are OFL and are not committed (several megabytes); pass --font-dir:

  unifont-18.0.01.otf
  fusion-pixel-10px-monospaced-zh_hans.ms.bitmap.ttf
  fusion-pixel-12px-monospaced-zh_hans.ms.bitmap.ttf

Run from the repository root:

  python3 tools/ui/generate_cjk_glyphs.py --font-dir /path/to/fonts
"""
from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

SMALL_SIZES = {10: 'fusion-pixel-10px-monospaced-zh_hans.ms.bitmap.ttf',
               12: 'fusion-pixel-12px-monospaced-zh_hans.ms.bitmap.ttf'}
WIDE_SIZE = 16
WIDE_FONT = 'unifont-18.0.01.otf'

# Every codepoint the port's own screens can print outside Latin. Anything
# below this is drawn by the existing Latin/Cyrillic font.
FIRST_CJK = 0x2E80

SOURCES = (
    'engine/src/ui_strings.c',
    'platform/3ds/source/game_languages.h',
)


def collect_ui_chars(root: Path) -> list[str]:
    chars: set[str] = set()
    for name in SOURCES:
        text = (root / name).read_text(encoding='utf-8')
        for ch in text:
            if ord(ch) >= FIRST_CJK:
                chars.add(ch)
    return sorted(chars)


def render(font: ImageFont.FreeTypeFont, ch: str, size: int) -> list[int]:
    """One glyph as rows of bits, most significant bit leftmost.

    Drawn on the font's own baseline inside a size x size cell: a character
    fills its square, and punctuation (, and .) sits at the bottom where it
    belongs instead of being centred like an ideograph.
    """
    image = Image.new('L', (size, size), 0)
    draw = ImageDraw.Draw(image)
    draw.text((0, 0), ch, font=font, fill=255, anchor='la')
    rows = []
    for y in range(size):
        bits = 0
        for x in range(size):
            if image.getpixel((x, y)) > 127:
                bits |= 1 << (size - 1 - x)
        rows.append(bits)
    return rows


def emit_table(out: list[str], c_type: str, name: str, size: int,
               chars: list[str], glyphs: list[list[int]]) -> None:
    dim = f'[{len(chars)}][{size}]'
    out.append(f'static const {c_type} {name}{dim} = {{')
    for ch, rows in zip(chars, glyphs):
        out.append('  {%s},  // %s U+%04X' % (','.join(str(r) for r in rows), ch, ord(ch)))
    out.append('};')
    out.append('')


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--font-dir', type=Path, default=Path('fonts'))
    parser.add_argument('--check', action='store_true',
                        help='fail when the generated header would change')
    args = parser.parse_args()

    root = Path(__file__).resolve().parents[2]
    ui_chars = collect_ui_chars(root)
    if not ui_chars:
        raise SystemExit('no Chinese characters found in the UI strings')
    wide_chars = ui_chars

    paths = dict(SMALL_SIZES)
    paths[WIDE_SIZE] = WIDE_FONT
    fonts = {}
    for size, name in paths.items():
        path = args.font_dir / name
        if not path.exists():
            raise SystemExit(f'missing font {path} (see --font-dir)')
        fonts[size] = ImageFont.truetype(str(path), size)

    narrow = {size: [render(fonts[size], ch, size) for ch in ui_chars]
              for size in SMALL_SIZES}
    wide = [render(fonts[WIDE_SIZE], ch, WIDE_SIZE) for ch in wide_chars]

    out = [
        '// Generated by tools/ui/generate_cjk_glyphs.py. Do not edit.',
        '#pragma once',
        '#include <stdint.h>',
        '',
        f'// {len(ui_chars)} characters, sorted by codepoint: exactly what the port\'s',
        '// own strings use, at the sizes its screens draw.',
        f'#define kUiCjkGlyphCount {len(ui_chars)}',
        f'#define kUiCjkFirstCodepoint 0x{FIRST_CJK:X}',
        '',
        'static const uint32_t kUiCjkCodepoints[kUiCjkGlyphCount] = {',
        *[f'  0x{ord(ch):04x},' for ch in ui_chars],
        '};',
        '',
    ]
    for size in (10, 12, 16):
        glyphs = narrow[size] if size in narrow else wide
        emit_table(out, 'uint16_t', f'kUiCjk{size}', size, ui_chars, glyphs)

    rendered = '\n'.join(out).rstrip('\n') + '\n'
    target = root / 'engine/src/platform/linux/ui_glyphs_cjk.h'
    if args.check:
        current = target.read_text(encoding='utf-8') if target.exists() else ''
        if current != rendered:
            raise SystemExit(f'{target} is out of date; rerun the generator')
        print(f'{target.name} is up to date ({len(wide_chars)} wide, {len(ui_chars)} small)')
        return
    target.write_text(rendered, encoding='utf-8')
    print(f'wrote {target} ({len(wide_chars)} wide, {len(ui_chars)} small, '
          f'{len(rendered) // 1024} KB)')


if __name__ == '__main__':
    main()
