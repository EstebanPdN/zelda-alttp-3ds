#!/usr/bin/env python3
"""Generate the Japanese UI glyph tables from the M+ bitmap faces.

Usage: generate_japanese_ui_glyphs.py PixelMplus10-Regular.ttf PixelMplus12-Regular.ttf

Only the characters the interface uses are kept. M+ FONTS is free to use, copy
and distribute with or without modification; see CREDITS.md.
"""
import pathlib
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCES = ("engine/src/ui_strings.c", "platform/3ds/source/game_languages.h")
OUT = ROOT / "engine/src/platform/linux/generated_ui_japanese.h"


def wanted():
    chars = set()
    for name in SOURCES:
        for ch in (ROOT / name).read_text(encoding="utf-8"):
            cp = ord(ch)
            if 0x3000 <= cp <= 0x9fff or 0xff00 <= cp <= 0xffef:
                chars.add(cp)
    return sorted(chars)


def rows(font, size, cp):
    image = Image.new("1", (size, size), 0)
    ImageDraw.Draw(image).text((0, 0), chr(cp), font=font, fill=1)
    out = []
    for y in range(size):
        bits = 0
        for x in range(size):
            bits = bits << 1 | (1 if image.getpixel((x, y)) else 0)
        out.append(bits)
    if cp != 0x3000 and not any(out):
        raise SystemExit(f"The font has no glyph for U+{cp:04X}")
    return out


def table(name, size, font_path, codes):
    font = ImageFont.truetype(font_path, size)
    lines = [f"static const uint16_t {name}[{len(codes)}][{size}] = {{"]
    for cp in codes:
        data = ",".join(f"0x{v:03x}" for v in rows(font, size, cp))
        lines.append(f"  {{{data}}}, // {chr(cp)}")
    lines.append("};")
    return lines


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    codes = wanted() or [0x3000]
    out = ["// Generated by tools/ui/generate_japanese_ui_glyphs.py; M+ FONTS PROJECT bitmap faces.",
           "#pragma once", "#include <stdint.h>", "",
           f"enum {{ kUiJapaneseGlyphCount = {len(codes)} }};",
           f"static const uint16_t kUiJapaneseCodepoints[{len(codes)}] = {{"]
    for i in range(0, len(codes), 12):
        out.append("  " + ",".join(f"0x{c:04x}" for c in codes[i:i + 12]) + ",")
    out.append("};")
    out += table("kUiJapaneseGlyphs10", 10, sys.argv[1], codes)
    out += table("kUiJapaneseGlyphs12", 12, sys.argv[2], codes)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(codes)} glyphs -> {OUT}")


if __name__ == "__main__":
    main()
